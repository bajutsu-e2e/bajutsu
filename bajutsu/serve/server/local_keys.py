"""Owner-only key files a local server start generates and keeps (BE-0449 unit 1).

A hosted deployment provisions its keys outside the process (``BAJUTSU_SECRETS_KEY``). A local
``bajutsu serve`` has no operator to do that, so it generates the secrets key and the HMAC key that
signs the ``file://`` store's URLs once, and keeps them in a state directory beside the runs
directory. A key that another local account can read or replace would undo BE-0136 on a shared host,
so the files follow the rules `bajutsu.common.run_meta.artifact_perms` applies to secret-bearing run
artifacts, tightened for a long-lived secret: created atomically as owner-only (``0600``) regular
files, and an existing path that is a symlink, not a regular file, owned by another account, or open
to group or other is refused rather than repaired, because by then its contents can no longer be
trusted.

`cryptography` (the ``db`` extra) is imported lazily, like the rest of the server's key handling.
"""

from __future__ import annotations

import os
import secrets
import stat
import tempfile
from collections.abc import Callable
from pathlib import Path

STATE_DIR_MODE = 0o700
KEY_FILE_MODE = 0o600

SECRETS_KEY_FILE = "secrets.key"
SIGNING_KEY_FILE = "store-signing.key"
# 256 bits matches HMAC-SHA256's block-independent security level; more buys nothing.
SIGNING_KEY_BYTES = 32


def local_state_dir(runs_dir: Path) -> Path:
    """The directory a local start keeps its generated keys in: ``.bajutsu`` beside the runs
    directory, so the keys travel with the project's run history and stay out of the run trees the
    UI lists and serves."""
    return runs_dir.parent / ".bajutsu"


def ensure_state_dir(path: Path) -> Path:
    """Create *path* (with parents) as an owner-only (``0700``) directory and return it.

    Raises:
        ValueError: *path* is a symlink or is owned by another account, or its existing
            ``.gitignore`` is a symlink or lacks the ``*`` line that keeps the keys uncommitted. As in `make_run_dir`, a
            pre-planted symlink would redirect the ``chmod`` (and every key file beneath it) onto a
            target another account controls, so it is refused, not followed.
        FileExistsError: *path* exists and is not a directory.
    """
    if path.is_symlink():
        raise ValueError(f"refusing to use a symlinked state directory: {path}")
    path.mkdir(parents=True, exist_ok=True)
    # mkdir(exist_ok=True) already raised FileExistsError if the path is anything but a directory.
    st = os.lstat(path)
    if st.st_uid != os.getuid():
        raise ValueError(f"refusing to use a state directory owned by another account: {path}")
    path.chmod(STATE_DIR_MODE)
    _ignore_everything(path)
    return path


def _ignore_everything(path: Path) -> None:
    # The state dir sits in the project root, so a `git add -A` there would otherwise commit the
    # keys. A self-ignoring `.gitignore` (as pytest and ruff caches use) keeps the whole dir out.
    # Written whole under a private name and then linked into place, so a concurrent start never
    # reads a created-but-still-empty file and fails the check below.
    gitignore = path / ".gitignore"
    fd, staged = tempfile.mkstemp(dir=path, prefix=".gitignore-")
    try:
        try:
            os.write(fd, b"# Generated by bajutsu serve: local keys, never commit.\n*\n")
        finally:
            os.close(fd)
        try:
            os.link(staged, gitignore)
        except FileExistsError:
            _check_ignores_everything(gitignore)
    finally:
        Path(staged).unlink()


def _check_ignores_everything(gitignore: Path) -> None:
    # A pre-existing file that no longer ignores `*` would let `git add -A` stage the keys, so it
    # fails closed before any key is created rather than being trusted by name.
    try:
        fd = os.open(gitignore, os.O_RDONLY | os.O_NOFOLLOW)
    except OSError as e:  # ELOOP: a symlink, refused rather than followed
        raise ValueError(
            f"refusing to use the state directory's .gitignore {gitignore}: {e}"
        ) from e
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise ValueError(f"refusing to use {gitignore}: it is not a regular file")
        chunks = []
        while chunk := os.read(fd, 4096):
            chunks.append(chunk)
    finally:
        os.close(fd)
    lines = b"".join(chunks).decode("utf-8", errors="replace").splitlines()
    if "*" not in (line.strip() for line in lines):
        raise ValueError(
            f"refusing to use the state directory: {gitignore} does not ignore everything "
            "(add a `*` line, or remove the file to have it regenerated)"
        )


def _unsafe_reason(st: os.stat_result) -> str | None:
    if stat.S_ISLNK(st.st_mode):
        return "it is a symlink"
    if not stat.S_ISREG(st.st_mode):
        return "it is not a regular file"
    if st.st_uid != os.getuid():
        return "it is owned by another account"
    if st.st_mode & 0o077:
        return f"its mode {stat.S_IMODE(st.st_mode):04o} grants group or other access (want 0600)"
    return None


def _read_existing(path: Path) -> bytes:
    reason = _unsafe_reason(os.lstat(path))
    if reason is not None:
        raise ValueError(f"refusing to use the key file {path}: {reason}")
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        # Re-check the opened file, not the name: a swap between the lstat and the open must not
        # hand back another file's bytes.
        reason = _unsafe_reason(os.fstat(fd))
        if reason is not None:
            raise ValueError(f"refusing to use the key file {path}: {reason}")
        chunks = []
        while chunk := os.read(fd, 4096):
            chunks.append(chunk)
    finally:
        os.close(fd)
    data = b"".join(chunks)
    if not data:
        raise ValueError(f"refusing to use the key file {path}: it is empty")
    return data


def _fsync_dir(path: Path) -> None:
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def load_or_create_key(path: Path, generate: Callable[[], bytes]) -> bytes:
    """The key stored at *path*, generating it with *generate* on first use.

    The new key is written to a uniquely named ``0600`` file opened with ``O_EXCL | O_NOFOLLOW``,
    synced, and then hard-linked into place. The link either creates *path* whole or fails because
    it exists, so a reader never sees a half-written key, and a concurrent start that loses the race
    reads the winner's key instead of writing its own.

    Raises:
        ValueError: an existing *path* is unsafe (a symlink, not a regular file, owned by another
            account, or open to group or other) or empty, or its parent directory is unsafe.
    """
    ensure_state_dir(path.parent)
    try:
        return _read_existing(path)
    except FileNotFoundError:
        pass
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{secrets.token_hex(8)}.tmp")
    fd = os.open(tmp, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, KEY_FILE_MODE)
    try:
        try:
            os.fchmod(fd, KEY_FILE_MODE)  # the umask can only narrow the open mode; pin it anyway
            data = generate()
            view = memoryview(data)
            while view:
                view = view[os.write(fd, view) :]
            os.fsync(fd)
        finally:
            os.close(fd)
        try:
            os.link(tmp, path)
        except FileExistsError:
            return _read_existing(path)
        _fsync_dir(path.parent)
        return data
    finally:
        tmp.unlink(missing_ok=True)


def secrets_key(state_dir: Path) -> bytes:
    """The local Fernet key that encrypts stored secrets, generated on first use.

    Raises:
        ValueError: the key file is unsafe, or holds something that is not a Fernet key.
    """
    from cryptography.fernet import Fernet

    path = state_dir / SECRETS_KEY_FILE
    key = load_or_create_key(path, Fernet.generate_key)
    try:
        Fernet(key)
    except ValueError as e:
        raise ValueError(f"the key file {path} does not hold a Fernet key") from e
    return key


def signing_key(state_dir: Path) -> bytes:
    """The local HMAC key that signs the ``file://`` store's URLs, generated on first use.

    Stored as the raw 32 bytes: nothing reads it but this function, so an encoding would only add a
    decode step that could fail.

    Raises:
        ValueError: the key file is unsafe, or does not hold exactly 32 bytes.
    """
    path = state_dir / SIGNING_KEY_FILE
    key = load_or_create_key(path, lambda: secrets.token_bytes(SIGNING_KEY_BYTES))
    if len(key) != SIGNING_KEY_BYTES:
        raise ValueError(f"the key file {path} does not hold a {SIGNING_KEY_BYTES}-byte key")
    return key
